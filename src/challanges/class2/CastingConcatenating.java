package challanges.class2;

public class CastingConcatenating {
    public static void main(String[] args) {
        // Casting
        double number1 = 10;
        double number2 = 5;
        double media = (number1 + number2) / 2;

        System.out.println("media = " + (int) media);

        // Concatenating
        char letter = 'J';
        String word = "ava";

        System.out.println(letter + word);
    }
}
